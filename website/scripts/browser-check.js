async (page) => {
  const failures=[]; const errors=[]; const checks=[];
  const check=(ok,name)=>{if(!ok)failures.push(name);else checks.push(name)};
  page.on('pageerror',e=>errors.push(String(e)));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
  await page.goto('http://127.0.0.1:4174/');
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('link',{name:'探索 Skill 架构',exact:true}).click();
  await page.getByRole('button',{name:'早期验证',exact:true}).click();
  check((await page.locator('.path-caption').textContent()).includes('S5 提出关键假设'),'Early validation routing copy');
  check(await page.locator('.highlight-path').count()===1,'Animated highlighted path');
  await page.getByRole('button',{name:'RAG 知识与检索',exact:true}).click();
  await page.locator('.graph-inspector h3').filter({hasText:'RAG 需求与架构'}).waitFor();
  check((await page.locator('.graph-inspector').textContent()).includes('知识来源与维护'),'RAG inspector content');
  await page.getByRole('button',{name:'放大架构图',exact:true}).click();
  check((await page.getByRole('button',{name:'重置架构缩放'}).textContent())==='110%','Zoom in');
  await page.getByRole('button',{name:'重置架构缩放'}).click();
  await page.locator('.architecture-shell').screenshot({path:'output/playwright/architecture.png'});
  await page.getByRole('button',{name:'打开完整使用指南',exact:true}).click();
  await page.locator('.guide-detail h3').filter({hasText:'RAG 需求与架构'}).waitFor();
  check((await page.locator('.guide-detail').textContent()).includes('$qaqpm-rag-requirements'),'Architecture to guide');
  const guideButtons=page.getByRole('navigation',{name:'Skill 指南'}).getByRole('button');
  check(await guideButtons.count()===17,'17 Skill guides');
  for(let i=0;i<17;i++){
    await guideButtons.nth(i).click();
    const name=(await guideButtons.nth(i).textContent()).replace(/^(CTRL|S\d+|AGENT|RAG|AIGC|RISK)/,'').trim();
    await page.locator('.guide-detail h3').filter({hasText:name}).waitFor();
    check((await page.locator('.guide-detail .command pre').textContent()).startsWith('$qaqpm-'),'Guide command '+name);
    check(await page.locator('.guide-detail .resource-kind.outline').count()===1,'Outline available '+name);
    check(await page.locator('.guide-detail .resource-kind.shared-rule').count()===1,'Shared rules available '+name);
  }
  await page.getByRole('navigation',{name:'Skill 指南'}).getByRole('button',{name:'RAG RAG 需求与架构'}).click();
  await page.locator('.guide-detail h3').filter({hasText:'RAG 需求与架构'}).waitFor();
  await page.context().grantPermissions(['clipboard-read','clipboard-write']);
  await page.locator('.guide-detail').getByRole('button',{name:'复制指令',exact:true}).click();
  check((await page.evaluate(()=>navigator.clipboard.readText())).startsWith('$qaqpm-rag-requirements'),'Copy invocation');
  await page.getByRole('button',{name:'查看 Skill 原文'}).click();
  await page.getByRole('dialog').getByRole('heading',{name:'QAQPM · RAG需求与架构',exact:true}).waitFor();
  check(await page.locator('dialog[open]').count()===1,'Native modal with fetched source');
  await page.getByRole('button',{name:'复制正文'}).click();
  check((await page.evaluate(()=>navigator.clipboard.readText())).startsWith('---\nname: qaqpm-rag-requirements'),'Copy exact original markdown');
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('link',{name:'下载原文件'}).click();
  const download=await downloadPromise;await download.saveAs('output/playwright/downloaded-SKILL.md');
  check(download.suggestedFilename()==='SKILL.md','Download source');
  await page.keyboard.press('Escape');
  check(await page.locator('dialog[open]').count()===0,'Escape closes modal');
  check(await page.getByRole('button',{name:'查看 Skill 原文'}).evaluate(el=>el===document.activeElement),'Dialog restores keyboard focus');
  await page.getByRole('button',{name:/我只想补一份文档/}).click();
  check((await page.locator('.scenario-result .command pre').textContent()).includes('只完成本次范围'),'Scenario prompt changes');
  for(let i=0;i<6;i++){
    await page.locator('.case-tabs button').nth(i).click();
    await page.locator('.case-controls .mono').filter({hasText:'0'+(i+1)+' / 06'}).waitFor();
    check((await page.locator('.case-artifact footer').textContent()).includes('非真实项目运行记录'),'Example evidence boundary '+(i+1));
  }
  await page.locator('.case-tabs button').nth(2).click();
  await page.locator('.case-artifact pre').filter({hasText:'not_run'}).waitFor();
  await page.waitForFunction(()=>+getComputedStyle(document.querySelector('.case-content')).opacity>.99);
  await page.locator('.case-section').screenshot({path:'output/playwright/case-study.png'});
  await page.getByRole('button',{name:'自动演示',exact:true}).click();
  await page.getByRole('button',{name:'暂停演示',exact:true}).click();
  check(await page.getByRole('button',{name:'自动演示',exact:true}).count()===1,'Play and pause controls');
  await page.getByRole('group',{name:'模板分类'}).getByRole('button',{name:'RAG',exact:true}).click();
  check(await page.locator('.template-card').count()===4,'RAG template filter');
  await page.getByRole('textbox',{name:'搜索模板'}).fill('知识来源');
  check(await page.locator('.template-card').count()===1,'Template search');
  await page.locator('.template-card').click();
  await page.locator('.markdown h1').waitFor();
  check((await page.locator('.markdown').textContent()).includes('知识来源'),'Rendered template');
  await page.getByRole('button',{name:'关闭文档预览'}).click();
  await page.getByRole('textbox',{name:'搜索模板'}).fill('不存在的模板xyz');
  check(await page.getByRole('heading',{name:'没有找到匹配的资料'}).count()===1,'No-result state');
  await page.getByRole('button',{name:'重置筛选'}).click();
  await page.getByRole('button',{name:'展开其余 75 项资料'}).click();
  check(await page.locator('.template-card').count()===84,'84 independent Markdown templates');
  await page.getByRole('button',{name:'收起资料'}).click();
  check((await page.locator('#templates .section-heading p').textContent()).includes('68 个字段模板与 16 个章节骨架'),'Detailed counts distinguish depth');
  await page.getByRole('button',{name:'文档写完，意味着技术已经通过验证吗？'}).click();
  check((await page.locator('.faq p').textContent()).includes('分别记录'),'FAQ expands');
  for (const width of [1440,1024,768,390,360]){
    await page.setViewportSize({width,height:900});
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), 'No page overflow at '+width);
  }
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:'output/playwright/mobile-home.png'});
  await page.getByRole('button',{name:'打开导航'}).click();
  await page.getByRole('navigation',{name:'主导航'}).getByRole('link',{name:'使用指南'}).click();
  check(await page.getByRole('button',{name:'打开导航'}).count()===1,'Mobile menu closes on navigation');
  await page.locator('.guide-detail').screenshot({path:'output/playwright/mobile-guide.png'});
  await page.emulateMedia({reducedMotion:'reduce'});
  check(await page.locator('.highlight-path').evaluate(el=>getComputedStyle(el).animationName)==='none','Reduced motion stops path animation');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'完整体系',exact:true}).click();
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:'output/playwright/desktop-home.png'});
  check(errors.length===0,'No browser console or page errors');
  return {passed:checks.length,failures,errors,checks};
}
